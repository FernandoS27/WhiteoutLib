"""IR -> pybind11 C++ emitter.

Consumes the same `BindModule` IR the Embind emitter does. The Python
extension is structured as one submodule per format (``whiteout.mdx``,
``whiteout.m2``, ``whiteout.m3``); each generated file defines one
``void bind<Module>(py::module_& m)`` function that the top-level
PYBIND11_MODULE entry calls.

Embind ↔ pybind11 mapping (key cases):

    enum_<E>("E").value(...)         ->  py::enum_<E>(m, "E").value(...)
    class_<C>(...).constructor<>()   ->  py::class_<C>(m, "C").def(py::init<>())
    .property("x", &C::x)            ->  .def_readwrite("x", &C::x)
    value_object<V>(...).field(...)  ->  py::class_<V>(m, "V") + .def_readwrite (no
                                          separate concept in pybind11)
    register_vector<T>("VecT")       ->  PYBIND11_MAKE_OPAQUE(std::vector<T>);
                                          py::bind_vector<...>(m, "VecT")
    constant("Name", v)              ->  m.attr("Name") = v
    typed_memory_view(...)           ->  py::memoryview::from_memory(...)

JS-side prefixes (`Mdx`, `M2`, `M3`) are stripped on the Python side: a
type already lives in ``whiteout.mdx``, so calling it ``MdxModel`` would
be redundant. The result is ``whiteout.mdx.Model``, ``whiteout.m2.Bone``,
etc.
"""

