# ── Python naming conventions ──────────────────────────────────────────────
# Fields and methods become snake_case; enum members and module-level
# constants become UPPER_SNAKE_CASE (PEP 8). Class names stay PascalCase.

_CAMEL_BOUNDARY_1 = re.compile(r'(.)([A-Z][a-z]+)')   # fooBar -> foo_Bar
_CAMEL_BOUNDARY_2 = re.compile(r'([a-z0-9])([A-Z])')  # ABCdef -> AB_Cdef


def to_snake_case(name: str) -> str:
    """`fooBar` / `FooBar` / `_foo_Bar` -> `foo_bar`. Idempotent on
    already-snake names. Acronyms collapse: `parseBLP` -> `parse_blp`."""
    if not name:
        return name
    s = _CAMEL_BOUNDARY_1.sub(r'\1_\2', name)
    s = _CAMEL_BOUNDARY_2.sub(r'\1_\2', s)
    return s.lower().replace('__', '_').strip('_')


def to_upper_snake(name: str) -> str:
    """`NoParent` -> `NO_PARENT`. `WrapWidth` -> `WRAP_WIDTH`. Already-
    upper-snake names pass through."""
    return to_snake_case(name).upper()


def _qualified(short: str, ns: str) -> str:
    if '::' in short and short.startswith(('whiteout::', 'std::')):
        return short
    return f'{ns}::{short}'


def _cpp_type(t: TypeRef, ns: str) -> str:
    if t.kind == TypeKind.PRIMITIVE:
        short = _short_name(t.cpp_text)
        if short in _WHITEOUT_PRIMITIVES:
            return f'whiteout::{short}'
        return t.cpp_text
    if t.kind == TypeKind.STRING:
        return 'std::string'
    if t.kind in (TypeKind.NESTED, TypeKind.ENUM):
        return t.cpp_text if '::' in t.cpp_text else _qualified(t.cpp_text, ns)
    if t.kind in (TypeKind.VECTOR, TypeKind.NESTED_VEC):
        return f'std::vector<{_cpp_type(t.element, ns)}>'
    if t.kind == TypeKind.ARRAY:
        return f'std::array<{_cpp_type(t.element, ns)}, {t.array_size}>'
    if t.kind == TypeKind.OPTIONAL:
        return f'std::optional<{_cpp_type(t.element, ns)}>'
    return t.cpp_text


def _py_name(js_name: str, prefix: str) -> str:
    """Convert Embind JS class name to Python name by stripping the prefix.

    `MdxModel` -> `Model`, `MdxLayerSubTexture` -> `LayerSubTexture`.
    Shared math types (no prefix) pass through unchanged.
    """
    if prefix and js_name.startswith(prefix) and js_name != prefix:
        rest = js_name[len(prefix):]
        # Make sure we don't strip into nothing or break a real name like
        # `MdxModel` -> `Model` — that's fine, but `MdxBone` -> `Bone` is too.
        return rest
    return js_name


