"""IR -> Python `.pyi` ambient stubs.

Produces one `.pyi` per module so that PyCharm/VSCode/mypy can offer
autocomplete + type checking for callers of the pybind11 extension.

Layout (PEP 561 stub package alongside the `.pyd` in the publishable
Python distribution):

    packages/python/whiteout-stubs/
        py.typed             ← from bindings/templates/python/
        __init__.pyi         ← from bindings/templates/python/
        mdx.pyi              ← generated by this emitter
        m2.pyi
        m3.pyi
        textures.pyi

`py.typed` and `__init__.pyi` are the hand-maintained surface that lives
in `bindings/templates/python/whiteout-stubs/` and is copied in at build
time by `scripts/build-python.ps1`.

Naming follows the same rules as the runtime pybind11 emitter
(`emit_pybind.py`): fields/methods snake_case, classes PascalCase, enum
members and module constants UPPER_SNAKE_CASE.
"""

from __future__ import annotations

from io import StringIO
from .ir import (
    BindClass, BindEnum, BindField, BindMethod, BindModule,
    TypeKind, TypeRef,
)
from .emit_pybind import (
    to_snake_case, to_upper_snake, _py_name, _py_enum_value_name,
)
from .parser import _short_name


_HEADER = '''# SPDX-License-Identifier: BSD-3-Clause
# AUTOGENERATED by tools/codegen/emit_pyi.py — do not edit by hand.
# Regenerate via:  python -m tools.codegen.codegen {module} --backend pyi

from __future__ import annotations
'''


# Math types live at the root `whiteout` package, exposed as plain classes
# in __init__.pyi. Submodules import them from there.
_SHARED_MATH = {'Vector2f', 'Vector3f', 'Vector4f', 'Quaternion'}


def _ts_to_py_primitive(short: str) -> str:
    if short in ('u8', 'u16', 'u32', 'u64', 'i8', 'i16', 'i32', 'i64'):
        return 'int'
    if short in ('f32', 'f64'):
        return 'float'
    if short == 'bool':
        return 'bool'
    return 'int'


def _strip_namespace(s: str) -> str:
    parts = s.split('::')
    while len(parts) > 1 and parts[0] and parts[0][0].islower():
        parts = parts[1:]
    return '::'.join(parts)


def _flatten_qualified(qual: str) -> str:
    parts = qual.split('::')
    if len(parts) > 1 and parts[-1].startswith(parts[-2]):
        parts = parts[:-2] + [parts[-1]]
    return ''.join(parts)


class _NameContext:
    """Resolves C++ qualifiers to Python class names + tracks shared imports."""
    def __init__(self, module: BindModule):
        self.prefix = module.js_prefix
        self.cpp_to_py: dict[str, str] = {}
        for e in module.enums:
            full = (f'{e.cpp_namespace}::{e.cpp_qualifier}'
                    if e.cpp_namespace else e.cpp_qualifier)
            self.cpp_to_py[full] = _py_name(e.js_name, self.prefix)
        for c in module.classes:
            full = (f'{c.cpp_namespace}::{c.cpp_qualifier}'
                    if c.cpp_namespace else c.cpp_qualifier)
            self.cpp_to_py[full] = _py_name(c.js_name, self.prefix)
        self.local_class_short_names = {
            _py_name(c.js_name, self.prefix) for c in module.classes
            if _py_name(c.js_name, self.prefix) not in _SHARED_MATH
        }
        self.shared_uses: set[str] = set()
        # Vector class names referenced by any field/method/track. Used to
        # emit a stub `class Name: ...` for every container the module
        # exposes — even shared ones that another TU actually binds — so
        # mypy can resolve names within this submodule.
        self.referenced_vectors: dict[str, TypeRef] = {}


def _py_type(t: TypeRef, ctx: _NameContext) -> str:
    if t.kind == TypeKind.PRIMITIVE:
        return _ts_to_py_primitive(_strip_namespace(t.cpp_text))
    if t.kind == TypeKind.STRING:
        return 'str'
    if t.kind == TypeKind.ENUM:
        py = ctx.cpp_to_py.get(t.cpp_text)
        if py is None:
            py = _flatten_qualified(_strip_namespace(t.cpp_text))
        return py
    if t.kind == TypeKind.NESTED:
        py = ctx.cpp_to_py.get(t.cpp_text)
        if py is None:
            short = _strip_namespace(t.cpp_text).replace('::', '')
            py = short
        if py in _SHARED_MATH:
            ctx.shared_uses.add(py)
        return py
    if t.kind == TypeKind.VECTOR:
        return _vector_class_for(t.element, ctx)
    if t.kind == TypeKind.NESTED_VEC:
        # std::vector<std::vector<T>> -> the outer container's class name
        # matches `Vector + js_name_for_type(inner_vector)`.
        return _vector_class_for(t.element, ctx)
    if t.kind == TypeKind.OPTIONAL:
        return f'{_py_type(t.element, ctx)} | None'
    if t.kind == TypeKind.ARRAY:
        return f'list[{_py_type(t.element, ctx)}]'
    return 'Any'


def _emit_docstring(buf: StringIO, doc: str, indent: str = '    '):
    """Emit a triple-quoted Python docstring inside a class/function body."""
    if not doc:
        buf.write(f'{indent}...\n')
        return
    if '\n' not in doc and '"""' not in doc:
        buf.write(f'{indent}"""{doc}"""\n')
        return
    safe = doc.replace('"""', "'''")
    buf.write(f'{indent}"""\n')
    for line in safe.splitlines():
        buf.write(f'{indent}{line}\n' if line else f'{indent}\n')
    buf.write(f'{indent}"""\n')


def _emit_module_docstring(buf: StringIO, doc: str):
    """Emit a module-level docstring before any imports."""
    if not doc:
        return
    buf.write(f'"""{doc}"""\n\n' if '\n' not in doc and '"""' not in doc
              else f'"""\n{doc}\n"""\n\n')


def _emit_constants(buf: StringIO, module: BindModule):
    if not module.constants:
        return
    buf.write('# ── Sentinel constants ─────────────────────────────────────────────\n')
    for c in module.constants:
        py_const = to_upper_snake(_py_name(c.js_name, module.js_prefix))
        if c.doc:
            buf.write(f'# {c.doc}\n')
        buf.write(f'{py_const}: int\n')
    buf.write('\n')


def _emit_enum(buf: StringIO, e: BindEnum, ctx: _NameContext):
    py_name = _py_name(e.js_name, ctx.prefix)
    buf.write(f'class {py_name}:\n')
    if e.doc:
        _emit_docstring(buf, e.doc)
    seen: set[str] = set()
    for v in e.values:
        py = _py_enum_value_name(v.js_name)
        if py in seen:
            continue
        seen.add(py)
        if v.doc:
            buf.write(f'    # {v.doc}\n')
        buf.write(f'    {py}: ClassVar[{py_name}]\n')
    if not seen and not e.doc:
        # all-empty: keep `...`
        buf.write('    ...\n')
    buf.write(f'    @property\n    def value(self) -> int: ...\n\n')


def _emit_class_body(buf: StringIO, c: BindClass, ctx: _NameContext):
    """Emit class members (fields, ctors, methods) — body of `class X:`."""
    array_helpers: list[BindField] = []
    body_lines: list[str] = []

    if c.doc:
        # docstring first, then class body
        _emit_docstring(buf, c.doc)

    # POD value_objects also expose a positional/kwargs ctor that matches
    # the field list (mirrors what emit_pybind emits via aggregate init).
    pod_ctor_sig: str | None = None
    if c.is_value_object and c.fields and all(
            f.type.kind == TypeKind.PRIMITIVE for f in c.fields):
        pod_ctor_sig = ', '.join(
            f'{to_snake_case(f.name)}: {_py_type(f.type, ctx)}'
            for f in c.fields
        )

    # Constructors. Multiple overloads need @overload; the no-arg variant
    # is always present.
    overloads: list[str] = ['']
    if pod_ctor_sig is not None:
        overloads.append(pod_ctor_sig)
    for ctor in c.constructors:
        overloads.append(', '.join(
            f'{p.name}: {_py_type(p.type, ctx)}' for p in ctor.params))

    if len(overloads) > 1:
        for sig in overloads:
            buf.write('    @overload\n')
            if sig:
                buf.write(f'    def __init__(self, {sig}) -> None: ...\n')
            else:
                buf.write('    def __init__(self) -> None: ...\n')
    else:
        buf.write('    def __init__(self) -> None: ...\n')

    # Fields.
    for f in c.fields:
        if f.type.kind == TypeKind.ARRAY:
            array_helpers.append(f)
            continue
        py_field = to_snake_case(f.name)
        py_type = _py_type(f.type, ctx)
        if f.doc:
            buf.write(f'    # {f.doc}\n')
        buf.write(f'    {py_field}: {py_type}\n')
        if f.array_with_view:
            buf.write(f'    def {py_field}_view(self) -> memoryview: ...\n')

    # std::array<T,N> fields are exposed as get_/set_.
    for f in array_helpers:
        elem = _py_type(f.type.element, ctx)
        py_field = to_snake_case(f.name)
        buf.write(f'    def get_{py_field}(self) -> list[{elem}]: ...\n')
        buf.write(f'    def set_{py_field}(self, values: list[{elem}]) -> None: ...\n')

    # Methods.
    for m in c.methods:
        py_name = to_snake_case(m.name)
        if m.bytes_in:
            params = ['self'] + [
                f'{p.name}: bytes' if i == 0 else
                f'{p.name}: {_py_type(p.type, ctx)}'
                for i, p in enumerate(m.params)
            ]
        else:
            params = ['self'] + [
                f'{p.name}: {_py_type(p.type, ctx)}' for p in m.params
            ]
        if m.bytes_out:
            ret = 'bytes'
        elif m.return_type.kind.value == 'optional':
            ret = _py_type(m.return_type.element, ctx)
        elif m.return_type.cpp_text == 'void':
            ret = 'None'
        else:
            ret = _py_type(m.return_type, ctx)
        sig = ', '.join(params)
        if m.doc:
            buf.write(f'    def {py_name}({sig}) -> {ret}:\n')
            _emit_docstring(buf, m.doc, indent='        ')
        else:
            buf.write(f'    def {py_name}({sig}) -> {ret}: ...\n')


def _emit_value_object(buf: StringIO, c: BindClass, ctx: _NameContext):
    name = _py_name(c.js_name, ctx.prefix)
    if name in _SHARED_MATH:
        return  # declared in __init__.pyi
    buf.write(f'class {name}:\n')
    _emit_class_body(buf, c, ctx)
    buf.write('\n')


def _emit_class(buf: StringIO, c: BindClass, ctx: _NameContext):
    name = _py_name(c.js_name, ctx.prefix)
    buf.write(f'class {name}:\n')
    _emit_class_body(buf, c, ctx)
    buf.write('\n')


def _vector_class_for(elem: TypeRef, ctx: _NameContext) -> str:
    """Match the per-vector class names emitted by the pybind11 backend
    (VectorU32, VectorVector3f, VectorMdxBone, ...).

    Side-effect: records the reference in ctx so the stub emitter can
    declare the class even when another TU actually binds it at runtime.
    """
    from .parser import js_name_for_type
    js = 'Vector' + js_name_for_type(elem, ctx.prefix)
    py = _py_name(js, ctx.prefix)
    if py not in ctx.referenced_vectors:
        # Reconstruct a TypeRef that describes the vector container itself
        # (so _emit_vector_classes can render its `append(...)` etc.).
        ctx.referenced_vectors[py] = TypeRef(
            cpp_text=f'std::vector<{elem.cpp_text}>',
            kind=TypeKind.VECTOR,
            element=elem,
        )
    return py


def _emit_vector_classes(buf: StringIO, module: BindModule, ctx: _NameContext):
    """Emit `class VectorXXX: ...` for every container referenced from this
    module's surface — locally-bound ones AND shared ones (VectorU32 etc.)
    that another TU actually registers at import. Stubs are evaluated per
    submodule, so we re-declare shared classes here rather than chasing
    cross-stub imports.

    The structural shape (`append`, `__iter__`, `__getitem__`, ...) matches
    the pybind11 vector wrapper at runtime."""
    # Seed referenced_vectors with every vector_types entry, then close
    # under nesting (rendering vector<vector<T>> may pull in vector<T>).
    from .parser import js_name_for_type
    for v in module.vector_types:
        js = 'Vector' + js_name_for_type(v.element, ctx.prefix)
        py_cls = _py_name(js, ctx.prefix)
        ctx.referenced_vectors.setdefault(py_cls, v)
    # Close under nesting: rendering each element type may register more.
    while True:
        before = len(ctx.referenced_vectors)
        for v in list(ctx.referenced_vectors.values()):
            _py_type(v.element, ctx)
        if len(ctx.referenced_vectors) == before:
            break
    by_class = dict(ctx.referenced_vectors)
    if not by_class:
        return
    buf.write('# ── Vector containers ──────────────────────────────────────────────\n')
    for py_cls in sorted(by_class):
        v = by_class[py_cls]
        elem = _py_type(v.element, ctx)
        buf.write(f'class {py_cls}:\n')
        buf.write('    def __init__(self) -> None: ...\n')
        buf.write(f'    def append(self, value: {elem}, /) -> None: ...\n')
        buf.write(f'    def extend(self, values: {py_cls}, /) -> None: ...\n')
        buf.write('    def clear(self) -> None: ...\n')
        buf.write(f'    def __iter__(self) -> Iterator[{elem}]: ...\n')
        buf.write('    def __len__(self) -> int: ...\n')
        buf.write(f'    def __getitem__(self, i: int, /) -> {elem}: ...\n')
        buf.write(f'    def __setitem__(self, i: int, value: {elem}, /) -> None: ...\n')
        buf.write('\n')


def emit(module: BindModule) -> str:
    out = StringIO()
    out.write(_HEADER.format(module=module.name))

    ctx = _NameContext(module)

    # Always-needed imports.
    out.write('from typing import Any, ClassVar, Iterator, overload\n')

    # Body in a temp buffer so we know which shared imports are used.
    body = StringIO()

    skip = set(module.skip_class_js_names)
    enums = [e for e in module.enums if e.js_name not in skip]
    value_classes = [c for c in module.classes
                     if c.is_value_object and c.js_name not in skip]
    other_classes = [c for c in module.classes
                     if not c.is_value_object and c.js_name not in skip]

    _emit_constants(body, module)

    if enums:
        body.write('# ── Enums ──────────────────────────────────────────────────────────\n')
        for e in enums:
            _emit_enum(body, e, ctx)

    if value_classes:
        body.write('# ── Value-object types ─────────────────────────────────────────────\n')
        for c in value_classes:
            _emit_value_object(body, c, ctx)

    if other_classes:
        body.write('# ── Classes ────────────────────────────────────────────────────────\n')
        for c in other_classes:
            _emit_class(body, c, ctx)

    _emit_vector_classes(body, module, ctx)

    # Shared imports come from the package root (`whiteout/__init__.pyi`).
    if ctx.shared_uses:
        names = sorted(ctx.shared_uses)
        out.write(f'from . import {", ".join(names)}\n')
    out.write('\n')
    out.write(body.getvalue())
    return out.getvalue()
