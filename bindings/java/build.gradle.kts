// Gradle build for the WhiteoutLib Java FFM bindings.
//
// Produces (under `build/libs/`):
//
//   whiteout-<ver>.jar                main classes + module-info
//   whiteout-<ver>-sources.jar        sources
//   whiteout-<ver>-javadoc.jar        javadoc
//   whiteout-<ver>-natives-<os>-<arch>.jar
//                                     packaged native at META-INF/native/<os>-<arch>/
//                                     (only when -PnativeLibPath= resolves to a real file)
//
// The published Maven coordinates default to:
//   io.github.sahmkow:whiteout:<ver>
// and for the host's natives:
//   io.github.sahmkow:whiteout:<ver>:natives-<os>-<arch>
//
// Use the standard tasks:
//
//   gradle build                      compile + assemble all jars
//   gradle test                       run the smoke tests
//   gradle publishToMavenLocal        install to ~/.m2/repository
//   gradle publish                    publish to the `target` repo (set
//                                     -PpublishUrl= -PpublishUsername= -PpublishPassword=)

plugins {
    `java-library`
    `maven-publish`
    signing
}

group   = (project.findProperty("group")      ?: "io.github.sahmkow").toString()
version = (project.findProperty("version")    ?: "0.1.0").toString()

// ── Source layout — points at the codegen output ────────────────────────
//
// The `bindings/java/src/main/java/` tree is autogenerated by
// tools/codegen/emit_java.py. `scripts/build-java.ps1` runs the codegen
// before invoking Gradle; running Gradle alone on a fresh checkout will
// compile whatever happens to be on disk.

java {
    toolchain {
        languageVersion = JavaLanguageVersion.of(
            (project.findProperty("javaToolchainVersion") ?: "22").toString().toInt(),
        )
    }
    withSourcesJar()
    withJavadocJar()
}

sourceSets {
    main {
        java {
            srcDirs("src/main/java")
        }
    }
    test {
        java {
            srcDirs("src/test/java")
        }
    }
}

// ── Tests ───────────────────────────────────────────────────────────────
//
// The hand-written tests under `src/test/java` use JUnit Jupiter; the
// `test` task runs them via the JUnit Platform launcher below.

testing {
