// ── Native library handling ─────────────────────────────────────────────
//
// The native library (`whiteout_native.{dll,so,dylib}`) is produced by
// CMake (`scripts/build-java.ps1` runs that step). When the configured
// path resolves to a real file we package it into a per-platform jar at
// META-INF/native/<os>-<arch>/, which user code can extract at runtime —
// or rely on `java.library.path` / `-Dwhiteout.native.path=…` instead.

val nativeLibPath: String? = project.findProperty("nativeLibPath") as String?
val nativeLibFile: File? = nativeLibPath?.let { file(it) }?.takeIf { it.exists() }

val nativeClassifier: String by lazy {
    project.findProperty("nativeClassifier") as String?
        ?: detectNativeClassifier()
}

fun detectNativeClassifier(): String {
    val os   = System.getProperty("os.name").lowercase()
    val arch = System.getProperty("os.arch").lowercase()

    val osTag = when {
        os.contains("windows") -> "windows"
        os.contains("mac") || os.contains("darwin") -> "macos"
        os.contains("linux") -> "linux"
        else -> os.replace(Regex("[^a-z0-9]+"), "")
    }
    val archTag = when (arch) {
        "amd64", "x86_64" -> "x86_64"
        "aarch64", "arm64" -> "aarch64"
        else -> arch
    }
    return "natives-$osTag-$archTag"
}

// Per-platform natives jar — packaged only when the native artefact exists.
val nativesJar by tasks.registering(Jar::class) {
    archiveClassifier.set(nativeClassifier)
    nativeLibFile?.let { lib ->
        // META-INF/native/<os>-<arch>/whiteout_native.<ext>
        val target = "META-INF/native/${nativeClassifier.removePrefix("natives-")}"
        from(lib) { into(target) }
    }
    onlyIf { nativeLibFile != null }
}

// Wire into `assemble` so `gradle build` produces the natives jar alongside
// the main / sources / javadoc jars (otherwise it only fires on publish).
tasks.named("assemble") { dependsOn(nativesJar) }

// ── Manifest / module info ──────────────────────────────────────────────

tasks.named<Jar>("jar") {
    manifest {
        attributes(
            "Implementation-Title"   to "WhiteoutLib Java bindings",
            "Implementation-Version" to project.version,
            "Implementation-Vendor"  to "Fernando Sahmkow",
            "Automatic-Module-Name"  to "whiteout",
        )
    }
}

tasks.named<JavaCompile>("compileJava") {
    // module-info.java is part of the source set; javac handles it directly.
    options.release.set(
        (project.findProperty("javaToolchainVersion") ?: "22").toString().toInt(),
    )
    options.encoding = "UTF-8"
    // Silence javac's module-system lint warnings — the codegen output
    // declares `requires` for every sibling module, which is correct but
    // triggers `-Xlint:module` advisories on transitive readability.
    options.compilerArgs.add("-Xlint:-module")
}

tasks.named<Javadoc>("javadoc") {
    (options as StandardJavadocDocletOptions).apply {
        addStringOption("Xdoclint:none", "-quiet")
        addBooleanOption("html5", true)
        // FFM types reference java.lang.foreign — make sure they're linkable.
        addStringOption("-link", "https://docs.oracle.com/en/java/javase/22/docs/api/")
    }
}

tasks.named<Test>("test") {
    useJUnitPlatform()
    nativeLibFile?.let { lib ->
        // Surface the staged native to the smoke test.
        systemProperty("whiteout.native.path", lib.absolutePath)
        jvmArgs("--enable-native-access=ALL-UNNAMED")
    }
}

// ── Publishing ──────────────────────────────────────────────────────────

publishing {
    publications {
        create<MavenPublication>("whiteout") {
            from(components["java"])
            artifact(nativesJar.get())

            pom {
                name.set("WhiteoutLib Java bindings")
                description.set(
                    "Java FFM bindings for WhiteoutLib — pure-C++ parsers/writers "
                        + "for Blizzard model, texture, and archive formats "
                        + "(MDX, M2, M3, BLP, DDS, PNG, JPEG, BMP, TGA, GIF, MPQ, CASC).",
                )
                url.set("https://github.com/Sahmkow/WhiteoutLib")
                licenses {
                    license {
                        name.set("BSD 3-Clause License")
                        url.set("https://opensource.org/licenses/BSD-3-Clause")
                    }
                }
                developers {
                    developer {
                        id.set("sahmkow")
                        name.set("Fernando Sahmkow")
                    }
                }
                scm {
                    url.set("https://github.com/Sahmkow/WhiteoutLib")
                    connection.set("scm:git:https://github.com/Sahmkow/WhiteoutLib.git")
                    developerConnection.set("scm:git:git@github.com:Sahmkow/WhiteoutLib.git")
                }
            }
        }
    }

    repositories {
        // Maven Central / Sonatype / GitHub Packages / private Nexus — pick at
        // publish time with -PpublishUrl=… -PpublishUsername=… -PpublishPassword=…
        // Without those props, `publish` falls back to the local Maven cache.
        val url = project.findProperty("publishUrl") as String?
        if (url != null) {
            maven {
                name = "external"
                setUrl(url)
                credentials {
                    username = project.findProperty("publishUsername") as String? ?: ""
                    password = project.findProperty("publishPassword") as String? ?: ""
                }
            }
        }
    }
}

signing {
    // Signing is opt-in: only kicks in when -Psigning.* GPG props are
    // configured (the standard Gradle signing-plugin convention) AND the
    // current task graph actually publishes to a remote Maven repo. The
    // PublishToMavenRepository type check catches the auto-generated
    // `publishWhiteoutPublicationTo<Repo>Repository` tasks too — a literal
    // `hasTask("publish")` would miss those.
    setRequired {
        gradle.taskGraph.allTasks.any {
            it is org.gradle.api.publish.maven.tasks.PublishToMavenRepository
        } && project.findProperty("signing.keyId") != null
    }
    sign(publishing.publications["whiteout"])
}

