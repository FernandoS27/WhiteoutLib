    group = "verification"
    description = "Print detected native classifier and library path."
    doLast {
        println("native classifier : $nativeClassifier")
        println("native library    : ${nativeLibFile?.absolutePath ?: "<not found>"}")
        println("group:artifact:ver: ${project.group}:${rootProject.name}:${project.version}")
    }
}
