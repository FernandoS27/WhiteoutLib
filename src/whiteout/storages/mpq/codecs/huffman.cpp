// ============================================================================
// Huffman tree structures
// ============================================================================

struct HTreeItem {
    HTreeItem* next = nullptr; // Links in the sorted-by-weight doubly-linked list.
    HTreeItem* prev = nullptr;
    u32 decompressedValue = 0; // Byte value this leaf represents (or 0 for internal nodes).
    u32 weight = 0;
    HTreeItem* parent = nullptr;
    HTreeItem* childLo = nullptr; // Lower-weight child (right child).

    void remove() {
        if (next) {
            prev->next = next;
            next->prev = prev;
            next = prev = nullptr;
        }
    }
};

struct QuickLink {
    u32 validValue = 0;
    u32 validBits = 0;
    union {
        HTreeItem* item;
        u32 decompressedValue;
    };
};

// ============================================================================
// Bit reader — LSB-first, matching StormLib's TInputStream.
// ============================================================================

struct HuffBitReader {
    const u8* data;
    const u8* end;
    u32 bitBuf = 0;
    u32 bitsAvail = 0;

    HuffBitReader(const u8* d, size_t s) : data(d), end(d + s) {}

    bool get1Bit(u32& val) {
        if (bitsAvail == 0) {
            if (data >= end)
                return false;
            bitBuf = *data++;
            bitsAvail = 8;
        }
        val = bitBuf & 1;
        bitBuf >>= 1;
        bitsAvail--;
        return true;
    }

    bool get8Bits(u32& val) {
        if (bitsAvail < 8) {
            if (data >= end)
                return false;
            bitBuf |= static_cast<u32>(*data++) << bitsAvail;
            bitsAvail += 8;
        }
        val = bitBuf & 0xFF;
        bitBuf >>= 8;
        bitsAvail -= 8;
        return true;
    }

    bool peek7Bits(u32& val) {
        if (bitsAvail < 7) {
            if (data >= end)
                return false;
            bitBuf |= static_cast<u32>(*data++) << bitsAvail;
            bitsAvail += 8;
        }
        val = bitBuf & 0x7F;
        return true;
    }

    void skipBits(u32 count) {
        if (bitsAvail < count) {
            if (data >= end)
                return;
            bitBuf |= static_cast<u32>(*data++) << bitsAvail;
            bitsAvail += 8;
        }
        bitBuf >>= count;
        bitsAvail -= count;
    }
};

// ============================================================================
// Huffman tree — implements the Blizzard adaptive Huffman algorithm.
// ============================================================================

struct HuffTree {
    HTreeItem itemPool[kHuffItemCount];
    u32 itemsUsed = 0;

    // List head sentinel: pFirst and pLast form a circular doubly-linked list.
    // LIST_HEAD() in StormLib is (THTreeItem*)(&pFirst).
    HTreeItem* pFirst = nullptr;
    HTreeItem* pLast = nullptr;

    HTreeItem* itemsByByte[0x102] = {};
    QuickLink quickLinks[kLinkItemCount] = {};
    u32 minValidValue = 1;
    u32 isCmp0 = 0;

    HTreeItem* listHead() {
        return reinterpret_cast<HTreeItem*>(&pFirst);
    }

    void init() {
        pFirst = listHead();
        pLast = listHead();
        itemsUsed = 0;
        minValidValue = 1;
        isCmp0 = 0;
        std::memset(itemsByByte, 0, sizeof(itemsByByte));
        std::memset(quickLinks, 0, sizeof(quickLinks));
    }

    void linkTwo(HTreeItem* item1, HTreeItem* item2) {
        item2->next = item1->next;
        item2->prev = item1->next->prev;
        item1->next->prev = item2;
        item1->next = item2;
    }

    void insertItem(HTreeItem* newItem, bool before, HTreeItem* insertPoint) {
        newItem->remove();
        if (!insertPoint)
            insertPoint = listHead();

        if (!before) {
            // InsertAfter
            linkTwo(insertPoint, newItem);
        } else {
            // InsertBefore
            newItem->next = insertPoint;
            newItem->prev = insertPoint->prev;
            insertPoint->prev->next = newItem;
            insertPoint->prev = newItem;
        }
    }

    HTreeItem* findHigherOrEqual(HTreeItem* item, u32 weight) {
        if (item) {
            while (item != listHead()) {
                if (item->weight >= weight)
                    return item;
                item = item->prev;
            }
        }
        return listHead();
    }

    HTreeItem* createItem(u32 value, u32 weight, bool before) {
        if (itemsUsed >= kHuffItemCount)
            return nullptr;
        HTreeItem* item = &itemPool[itemsUsed++];
        item->next = item->prev = nullptr;
        item->decompressedValue = value;
        item->weight = weight;
        item->parent = nullptr;
        item->childLo = nullptr;
        insertItem(item, before, nullptr);
        return item;
    }

    u32 fixupPosition(HTreeItem* item, u32 maxWeight) {
        if (item->weight < maxWeight) {
            HTreeItem* higher = findHigherOrEqual(pLast, item->weight);
            item->remove();
            linkTwo(higher, item);
        } else {
            maxWeight = item->weight;
        }
        return maxWeight;
    }

    bool buildTree(u32 compType) {
        std::memset(itemsByByte, 0, sizeof(itemsByByte));
        u32 maxWeight = 0;

        if ((compType & 0x0F) > 0x08)
            return false;
        const u8* weights = kWeightTables[compType & 0x0F];

        for (u32 i = 0; i < 0x100; i++) {
            if (weights[i] != 0) {
                itemsByByte[i] = createItem(i, weights[i], false);
                maxWeight = fixupPosition(itemsByByte[i], maxWeight);
            }
        }

        // Terminal and new-branch entries.
        itemsByByte[0x100] = createItem(0x100, 1, true);
        itemsByByte[0x101] = createItem(0x101, 1, true);

        // Build the binary tree bottom-up from the sorted list.
        HTreeItem* childLo = pLast;
        while (childLo != listHead()) {
            HTreeItem* childHi = childLo->prev;
            if (childHi == listHead())
                break;

            HTreeItem* parent = createItem(0, childHi->weight + childLo->weight, false);
            if (!parent)
                return false;

            childLo->parent = parent;
            childHi->parent = parent;
            parent->childLo = childLo;

            maxWeight = fixupPosition(parent, maxWeight);
            childLo = childHi->prev;
        }

        minValidValue = 1;
        return true;
    }

    void incWeightsAndRebalance(HTreeItem* item) {
        for (; item != nullptr; item = item->parent) {
            item->weight++;

            HTreeItem* higher = findHigherOrEqual(item->prev, item->weight);
            HTreeItem* childHi = higher->next;

            if (childHi != item) {
                childHi->remove();
                linkTwo(item, childHi);

                item->remove();
                linkTwo(higher, item);

                HTreeItem* childLo2 = childHi->parent->childLo;
                HTreeItem* par = item->parent;
                if (par->childLo == item)
                    par->childLo = childHi;
                if (childLo2 == childHi)
                    childHi->parent->childLo = item;
                par = item->parent;
                item->parent = childHi->parent;
                childHi->parent = par;

                minValidValue++;
            }
        }
    }

    bool insertNewBranch(u32 value1, u32 value2) {
        HTreeItem* lastItem = pLast;

        HTreeItem* childHi = createItem(value1, lastItem->weight, true);
        if (!childHi)
            return false;
        childHi->parent = lastItem;
        itemsByByte[value1] = childHi;

        HTreeItem* childLo = createItem(value2, 0, true);
        if (!childLo)
            return false;
        childLo->parent = lastItem;
        lastItem->childLo = childLo;
        itemsByByte[value2] = childLo;

        incWeightsAndRebalance(childLo);
        return true;
    }

    u32 decodeOneByte(HuffBitReader& is) {
        HTreeItem* itemLink = nullptr;
        u32 linkIndex = 0;
        u32 bitCount = 0;

        bool hasLink = is.peek7Bits(linkIndex);

        HTreeItem* item;
        if (hasLink && quickLinks[linkIndex].validValue > minValidValue) {
            if (quickLinks[linkIndex].validBits <= 7) {
                is.skipBits(quickLinks[linkIndex].validBits);
                return quickLinks[linkIndex].decompressedValue;
            }
            item = quickLinks[linkIndex].item;
            is.skipBits(7);
        } else {
            if (pFirst == listHead())
                return kDecompressError;
            item = pFirst;
        }

        while (item->childLo != nullptr) {
            u32 bitVal = 0;
            if (!is.get1Bit(bitVal))
                return kDecompressError;
            item = bitVal ? item->childLo->prev : item->childLo;
            bitCount++;
            if (bitCount == 7)
                itemLink = item;
        }

        if (hasLink && quickLinks[linkIndex].validValue < minValidValue) {
            if (bitCount > 7) {
                quickLinks[linkIndex].validValue = minValidValue;
                quickLinks[linkIndex].validBits = bitCount;
                quickLinks[linkIndex].item = itemLink;
            } else {
                u32 idx = (bitCount != 0) ? linkIndex & (0xFFFFFFFF >> (32 - bitCount)) : 0;
                while (idx < kLinkItemCount) {
                    quickLinks[idx].validValue = minValidValue;
                    quickLinks[idx].validBits = bitCount;
                    quickLinks[idx].decompressedValue = item->decompressedValue;
                    idx += (1u << bitCount);
                }
            }
        }

        return item->decompressedValue;
    }
};

