namespace {

struct HuffBitWriter {
    std::vector<u8>& out;
    u32 bitBuf = 0;
    u32 bitsUsed = 0;

    HuffBitWriter(std::vector<u8>& o) : out(o) {}

    void put1Bit(u32 val) {
        bitBuf |= (val & 1) << bitsUsed;
        bitsUsed++;
        if (bitsUsed >= 8) {
            out.push_back(static_cast<u8>(bitBuf & 0xFF));
            bitBuf >>= 8;
            bitsUsed -= 8;
        }
    }

    void put8Bits(u32 val) {
        bitBuf |= (val & 0xFF) << bitsUsed;
        bitsUsed += 8;
        while (bitsUsed >= 8) {
            out.push_back(static_cast<u8>(bitBuf & 0xFF));
            bitBuf >>= 8;
            bitsUsed -= 8;
        }
    }

    void flush() {
        if (bitsUsed > 0) {
            out.push_back(static_cast<u8>(bitBuf & 0xFF));
            bitBuf = 0;
            bitsUsed = 0;
        }
    }
};

// Encode a value by walking from the leaf to root and emitting bits.
// childLo child = bit 0, childHi (childLo->prev) = bit 1
void encodeValue(HuffTree& tree, HuffBitWriter& bw, u32 value) {
    HTreeItem* leaf = tree.itemsByByte[value];
    if (!leaf)
        return;

    // Collect bits from leaf to root.
    std::array<u32, 64> bits;
    u32 bitCount = 0;

    HTreeItem* item = leaf;
    while (item->parent != nullptr) {
        HTreeItem* par = item->parent;
        // childLo = 0, childHi (childLo->prev) = 1
        bits[bitCount++] = (item == par->childLo) ? 0 : 1;
        item = par;
        if (bitCount >= 64)
            break;
    }

    // Emit bits in reverse order (root-first becomes LSB-first).
    for (u32 i = bitCount; i > 0; i--) {
        bw.put1Bit(bits[i - 1]);
    }
}

} // anonymous namespace

std::vector<u8> huffmanCompress(std::span<const u8> src, u32 compType) {
    if (src.empty())
        return {};

    std::vector<u8> out;
    out.reserve(src.size() + 16);

    HuffBitWriter bw(out);

    // Write compression type byte.
    bw.put8Bits(compType);

    // Build tree with same logic as decompressor.
    HuffTree tree;
    tree.init();
    tree.isCmp0 = (compType == 0) ? 1 : 0;
    if (!tree.buildTree(compType))
        return {};

    for (size_t i = 0; i < src.size(); i++) {
        u8 byte = src[i];

        if (tree.itemsByByte[byte] != nullptr) {
            // Symbol already in tree — encode it.
            encodeValue(tree, bw, byte);
        } else {
            // New symbol — encode 0x101 (new-branch marker), then the raw 8-bit value.
            encodeValue(tree, bw, 0x101);
            bw.put8Bits(byte);

            tree.insertNewBranch(tree.pLast->decompressedValue, byte);
            if (tree.isCmp0 == 0) {
                tree.incWeightsAndRebalance(tree.itemsByByte[byte]);
            }
        }

        if (tree.isCmp0) {
            tree.incWeightsAndRebalance(tree.itemsByByte[byte]);
        }
    }

    // Encode end-of-stream (0x100).
    encodeValue(tree, bw, 0x100);
    bw.flush();

    return out;
}

